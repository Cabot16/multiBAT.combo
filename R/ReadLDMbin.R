# ============================================================
# ReadLDMbin.R
#
# Resolve and read a gene-specific GCTB full LD matrix.
#
# Gene-to-LD file matching rules are defined centrally in
# input_validation.R through .resolve_ld_prefix().
#
# This function receives an LD directory and a gene identifier,
# resolves the corresponding LD prefix, reads the GCTB .info and
# .bin files, checks their consistency, and returns the LD matrix
# together with the LD information and resolved prefix.
# ============================================================


#' Read a Gene-specific GCTB Full LD Matrix
#'
#' Reads a full linkage disequilibrium (LD) matrix generated by GCTB for one
#' gene.
#'
#' The function receives an LD directory and a gene identifier. The actual
#' GCTB LD prefix is resolved using the package-wide gene-to-LD matching rules
#' defined by \code{.resolve_ld_prefix()} in \code{input_validation.R}.
#'
#' For example, given:
#'
#' \code{ld_dir = "/path/pop1"}
#'
#' and:
#'
#' \code{gene = "GENE1"}
#'
#' the resolved files may be:
#'
#' \code{/path/pop1/GENE1.ldm.full.info}
#'
#' and:
#'
#' \code{/path/pop1/GENE1.ldm.full.bin},
#'
#' or another uniquely resolved prefix such as:
#'
#' \code{/path/pop1/GENE1.EUR.ldm.full.info}
#'
#' and:
#'
#' \code{/path/pop1/GENE1.EUR.ldm.full.bin}.
#'
#' Gene-to-LD uniqueness rules are not implemented independently in this
#' function. They are defined centrally by \code{.resolve_ld_prefix()} so that
#' input validation and LD reading use exactly the same matching behaviour.
#'
#' If no complete LD file pair is available for the gene, the function returns
#' \code{NULL}. If the matched LD files cannot be read or are internally
#' inconsistent, the function also returns \code{NULL}. Ambiguous
#' gene-to-LD matching is handled by \code{.resolve_ld_prefix()} and stops the
#' analysis.
#'
#' @param ld_dir Character string giving the directory containing
#'   gene-specific GCTB full LD files.
#' @param gene Character string giving the gene identifier to be matched.
#' @param pop_label Character string used in diagnostic messages. Defaults to
#'   \code{"LD"}.
#'
#' @return If successful, returns a list containing:
#'
#'   \itemize{
#'     \item \code{LD}: the numeric LD matrix.
#'     \item \code{info}: the corresponding GCTB LD information table.
#'     \item \code{prefix}: the uniquely resolved full LD prefix ending in
#'       \code{.ldm.full}.
#'   }
#'
#'   Returns \code{NULL} if no usable LD matrix is available for the gene.
#'
#' @export
#
#' @examples
#' \dontrun{
#' ld_object <- ReadLDMbin(
#'   ld_dir = "/path/pop1",
#'   gene = "GENE1",
#'   pop_label = "POP1"
#' )
#'
#' if (!is.null(ld_object)) {
#'   LD <- ld_object$LD
#'   info <- ld_object$info
#'   prefix <- ld_object$prefix
#' }
#' }
ReadLDMbin <- function(
    ld_dir,
    gene,
    pop_label = "LD"
) {

    # Validate inputs and resolve LD prefix

    if (
        !is.character(ld_dir) ||
        length(ld_dir) != 1L ||
        is.na(ld_dir) ||
        !nzchar(trimws(ld_dir))
    ) {
        stop(
            "'ld_dir' must be a non-empty character value of length 1.",
            call. = FALSE
        )
    }


    if (
        !is.character(gene) ||
        length(gene) != 1L ||
        is.na(gene) ||
        !nzchar(trimws(gene))
    ) {
        stop(
            "'gene' must be a non-empty character value of length 1.",
            call. = FALSE
        )
    }


    if (
        !is.character(pop_label) ||
        length(pop_label) != 1L ||
        is.na(pop_label) ||
        !nzchar(trimws(pop_label))
    ) {
        stop(
            "'pop_label' must be a non-empty character value of length 1.",
            call. = FALSE
        )
    }


    if (!dir.exists(ld_dir)) {
        stop(
            paste0(
                "LD directory not found: ",
                ld_dir
            ),
            call. = FALSE
        )
    }


    prefix <- .resolve_ld_prefix(
        ld_dir = ld_dir,
        gene = gene,
        pop_label = pop_label
    )


    if (
        length(prefix) != 1L ||
        is.na(prefix)
    ) {
        return(
            NULL
        )
    }


    # Read GCTB LD files

    InfoFile <- paste0(
        prefix,
        ".info"
    )

    BinFile <- paste0(
        prefix,
        ".bin"
    )


    if (!file.exists(InfoFile)) {
        return(
            NULL
        )
    }


    if (!file.exists(BinFile)) {
        return(
            NULL
        )
    }


    info <- tryCatch(
        data.table::fread(
            InfoFile,
            header = TRUE,
            showProgress = FALSE
        ),
        error = function(e) {
            NULL
        }
    )


    if (is.null(info)) {
        return(
            NULL
        )
    }


    # Validate and read LD matrix

    m <- nrow(
        info
    )


    if (m <= 0L) {
        return(
            NULL
        )
    }


    expected_size <- m *
        m *
        4


    observed_size <- file.info(
        BinFile
    )$size


    if (
        length(observed_size) != 1L ||
        is.na(observed_size) ||
        observed_size != expected_size
    ) {
        return(
            NULL
        )
    }


    bin_con <- tryCatch(
        file(
            BinFile,
            "rb"
        ),
        error = function(e) {
            NULL
        }
    )


    if (is.null(bin_con)) {
        return(
            NULL
        )
    }


    on.exit(
        {
            if (isOpen(bin_con)) {
                close(
                    bin_con
                )
            }
        },
        add = TRUE
    )


    vals <- tryCatch(
        readBin(
            bin_con,
            what = numeric(0),
            n = m * m,
            size = 4,
            endian = "little"
        ),
        error = function(e) {
            numeric()
        }
    )


    if (length(vals) != m * m) {
        return(
            NULL
        )
    }


    LD <- matrix(
        vals,
        nrow = m,
        ncol = m,
        byrow = TRUE
    )


    # Return output

    list(
        LD = LD,
        info = info,
        prefix = prefix
    )
}